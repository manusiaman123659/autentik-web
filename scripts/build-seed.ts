import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { products } from "@/lib/data/products";
import { brands } from "@/lib/data/brands";
import { careerPositions } from "@/lib/data/careers";
import { articles } from "@/lib/data/news";
import { teamMembers } from "@/lib/data/team";
import { groups } from "@/lib/data/groups";
import { partners } from "@/lib/data/partners";

const out = resolve(process.cwd(), "supabase", "seed.sql");
mkdirSync(dirname(out), { recursive: true });

const esc = (s: string): string => s.replace(/'/g, "''");
const q = (s: string | null | undefined = ""): string => "'" + esc(s ?? "") + "'";
const json = (s: unknown): string => "'" + esc(JSON.stringify(s ?? [])) + "'::jsonb";
const slugify = (s: string): string =>
  s.toLowerCase().split(/[^a-z0-9]+/).filter(Boolean).join("-") || "x";

const L: string[] = [];
L.push("-- =============================================================================");
L.push("-- Autentik CMS - SQL seed data");
L.push("-- Autogenerated by 'npm run seed:build' from lib/data/*. Do not edit by hand.");
L.push("-- Paste into the Supabase SQL editor (or apply via CLI).");
L.push("-- =============================================================================");
L.push("begin;");

L.push("");
L.push("-- ---------------------------------------------------------- product_categories");
const cats = new Map<string, string>();
for (const p of products) if (!cats.has(p.category)) cats.set(p.category, p.categoryColor);
for (const [name, color] of cats) {
  L.push(
    `insert into public.product_categories (id, name, color) values (${q(
      slugify(name)
    )}, ${q(name)}, ${q(color)}) on conflict (id) do update set name = excluded.name, color = excluded.color;`
  );
}

L.push("");
L.push("-- ---------------------------------------------------------- brands");
brands.forEach((b, i) => {
  L.push(
    `insert into public.brands (id, name, segment, segment_color, tagline, description, accent_color, logo_light, logo_dark, is_active, sort_order) values (${q(
      b.id
    )}, ${q(b.name)}, ${q(b.segment)}, ${q(b.segmentColor)}, ${q(b.tagline)}, ${q(
      b.description
    )}, ${q(b.accentColor)}, ${q(b.logoLight)}, ${q(b.logoDark)}, true, ${i}) ` +
      `on conflict (id) do update set name = excluded.name, segment = excluded.segment, segment_color = excluded.segment_color, tagline = excluded.tagline, description = excluded.description, accent_color = excluded.accent_color, logo_light = excluded.logo_light, logo_dark = excluded.logo_dark, sort_order = excluded.sort_order;`
  );
});

L.push("");
L.push("-- ---------------------------------------------------------- products");
products.forEach((p, i) => {
  L.push(
    `insert into public.products (id, slug, name, brand_id, brand, brand_color, category, category_color, description, features, specs, image_url, gallery, related_ids, sort_order, is_active, status, product_type, seo_title, seo_description, og_image) values (${q(
      p.id
    )}, ${q(p.slug)}, ${q(p.name)}, ${q(slugify(p.brand))}, ${q(p.brand)}, ${q(
      p.brandColor
    )}, ${q(p.category)}, ${q(p.categoryColor)}, ${q(p.description)}, ${json(
      p.features ?? []
    )}, ${json(p.specs ?? [])}, ${q(p.imageUrl ?? "")}, ${json(p.images ?? [])}, ${json(
      [] as string[]
    )}, ${i}, true, 'published', 'b2b_system', '', '', '') ` +
      `on conflict (id) do update set slug = excluded.slug, name = excluded.name, brand_id = excluded.brand_id, brand = excluded.brand, brand_color = excluded.brand_color, category = excluded.category, category_color = excluded.category_color, description = excluded.description, features = excluded.features, specs = excluded.specs, image_url = excluded.image_url, gallery = excluded.gallery, sort_order = excluded.sort_order;`
  );
});

L.push("");
L.push("-- ---------------------------------------------------------- careers");
careerPositions.forEach((c, i) => {
  L.push(
    `insert into public.careers (id, slug, title, department, location, type, type_badge_color, summary, description, responsibilities, requirements, benefits, status, sort_order) values (${q(
      c.slug
    )}, ${q(c.slug)}, ${q(c.title)}, ${q(c.department)}, ${q(c.location)}, ${q(
      c.type
    )}, ${q(c.typeBadgeColor)}, ${q(c.summary)}, ${q(c.description)}, ${json(
      c.responsibilities
    )}, ${json(c.requirements)}, ${json(c.benefits)}, 'open', ${i}) ` +
      `on conflict (id) do update set title = excluded.title, department = excluded.department, location = excluded.location, type = excluded.type, type_badge_color = excluded.type_badge_color, summary = excluded.summary, description = excluded.description, responsibilities = excluded.responsibilities, requirements = excluded.requirements, benefits = excluded.benefits, sort_order = excluded.sort_order;`
  );
});

L.push("");
L.push("-- ---------------------------------------------------------- articles");
articles.forEach((a, i) => {
  L.push(
    `insert into public.articles (id, slug, badge, badge_color, category, date, title, excerpt, content, image_url, featured, is_visible, sort_order) values (${q(
      a.slug
    )}, ${q(a.slug)}, ${q(a.badge)}, ${q(a.badgeColor)}, null::text, ${q(a.date)}, ${q(
      a.title
    )}, ${q(a.excerpt)}, ${q(a.content)}, ${q(a.imageUrl ?? "")}, ${
      a.featured ? "true" : "false"
    }, true, ${i}) ` +
      `on conflict (id) do update set badge = excluded.badge, badge_color = excluded.badge_color, date = excluded.date, title = excluded.title, excerpt = excluded.excerpt, content = excluded.content, image_url = excluded.image_url, featured = excluded.featured, sort_order = excluded.sort_order;`
  );
});

L.push("");
L.push("-- ---------------------------------------------------------- team_members");
teamMembers.forEach((m, i) => {
  L.push(
    `insert into public.team_members (id, name, role, role_color, bio, image_url, is_visible, sort_order) values (${q(
      m.id
    )}, ${q(m.name)}, ${q(m.role)}, ${q(m.roleColor)}, ${q(m.bio)}, ${q(
      m.imageUrl ?? ""
    )}, true, ${i}) ` +
      `on conflict (id) do update set name = excluded.name, role = excluded.role, role_color = excluded.role_color, bio = excluded.bio, image_url = excluded.image_url, sort_order = excluded.sort_order;`
  );
});

L.push("");
L.push("-- ---------------------------------------------------------- group_companies");
groups.forEach((g, i) => {
  L.push(
    `insert into public.group_companies (id, name, legal_name, logo_url, url, is_visible, sort_order) values (${q(
      g.id
    )}, ${q(g.name)}, ${q(g.legalName ?? "")}, ${q(g.logoUrl ?? "")}, ${q(
      g.url ?? ""
    )}, true, ${i}) ` +
      `on conflict (id) do update set name = excluded.name, legal_name = excluded.legal_name, logo_url = excluded.logo_url, url = excluded.url, sort_order = excluded.sort_order;`
  );
});

L.push("");
L.push("-- ---------------------------------------------------------- partners");
partners.forEach((p, i) => {
  L.push(
    `insert into public.partners (id, name, short_name, logo_url, url, is_visible, sort_order) values (${q(
      p.id
    )}, ${q(p.name)}, ${q(p.shortName)}, ${q(p.logoUrl ?? "")}, ${q(p.url ?? "")}, true, ${i}) ` +
      `on conflict (id) do update set name = excluded.name, short_name = excluded.short_name, logo_url = excluded.logo_url, url = excluded.url, sort_order = excluded.sort_order;`
  );
});

L.push("commit;");

writeFileSync(out, L.join("\n") + "\n", "utf8");
console.log("wrote " + out);
console.log(
  "brands: " + brands.length + ", products: " + products.length + ", careers: " +
    careerPositions.length + ", articles: " + articles.length + ", team: " +
    teamMembers.length + ", groups: " + groups.length + ", partners: " + partners.length
);